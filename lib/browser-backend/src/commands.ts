export interface Patient {
  id: number;
  mrn: string;
  first_name: string;
  last_name: string;
  date_of_birth: string | null;
  sex: string | null;
  ethnicity: string | null;
  referral_reason: string | null;
  clinician_id: number | null;
  clinician_key: string | null;
  created_at: string;
  updated_at: string;
}

export interface CreatePatientInput {
  mrn: string;
  first_name: string;
  last_name: string;
  date_of_birth?: string | null;
  sex?: string | null;
  ethnicity?: string | null;
  referral_reason?: string | null;
  clinician_key?: string | null;
}

export function list_patients(args?: { search?: string }): Patient[] {
  const search = args?.search;
  if (search) {
    const pattern = `%${search}%`;
    return query<Patient>(
      "SELECT id, mrn, first_name, last_name, date_of_birth, sex, ethnicity, referral_reason, clinician_id, clinician_key, created_at, updated_at FROM patients WHERE first_name LIKE ? OR last_name LIKE ? OR mrn LIKE ? ORDER BY last_name, first_name",
      [pattern, pattern, pattern]
    );
  }
  return query<Patient>(
    "SELECT id, mrn, first_name, last_name, date_of_birth, sex, ethnicity, referral_reason, clinician_id, clinician_key, created_at, updated_at FROM patients ORDER BY last_name, first_name"
  );
}

export function get_patient(args: { id: number }): Patient {
  const patient = queryOne<Patient>(
    "SELECT id, mrn, first_name, last_name, date_of_birth, sex, ethnicity, referral_reason, clinician_id, clinician_key, created_at, updated_at FROM patients WHERE id = ?",
    [args.id]
  );
  if (!patient) throw new Error("Patient not found");
  return patient;
}

export function create_patient(args: CreatePatientInput): Patient {
  exec(
    "INSERT INTO patients (mrn, first_name, last_name, date_of_birth, sex, ethnicity, referral_reason, clinician_key, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, datetime('now'), datetime('now'))",
    [
      args.mrn,
      args.first_name,
      args.last_name,
      args.date_of_birth ?? null,
      args.sex ?? null,
      args.ethnicity ?? null,
      args.referral_reason ?? null,
      args.clinician_key ?? null,
    ]
  );
  const id = lastInsertRowId();
  return get_patient({ id });
}

export function update_patient(args: {
  id: number;
  input: Partial<CreatePatientInput>;
}): Patient {
  const existing = get_patient({ id: args.id });
  const merged = { ...existing, ...args.input };
  exec(
    "UPDATE patients SET mrn = ?, first_name = ?, last_name = ?, date_of_birth = ?, sex = ?, ethnicity = ?, referral_reason = ?, clinician_key = ?, updated_at = datetime('now') WHERE id = ?",
    [
      merged.mrn,
      merged.first_name,
      merged.last_name,
      merged.date_of_birth ?? null,
      merged.sex ?? null,
      merged.ethnicity ?? null,
      merged.referral_reason ?? null,
      merged.clinician_key ?? null,
      args.id,
    ]
  );
  return get_patient({ id: args.id });
}

export function delete_patient(args: { id: number }): void {
  const patient = queryOne<{ id: number }>(
    "SELECT id FROM patients WHERE id = ?",
    [args.id]
  );
  if (!patient) throw new Error("Patient not found");
  exec("DELETE FROM patients WHERE id = ?", [args.id]);
}


/**
 * Pedigree PRO — Browser Backend Commands
 *
 * TypeScript port of the Rust command handlers from commands.rs.
 * Uses sql.js (WASM SQLite) via the db.ts module.
 *
 * All mutations include cryptographic signatures where applicable,
 * matching the Rust backend behavior.
 */

import { exec, query, queryOne, lastInsertRowId, getCachedDeviceId } from "./db";
import { computeHash } from "@workspace/crypto";
import { listProfilePrivateKeys } from "./crypto-store";

function withTransaction<T>(fn: () => T): T {
  exec("BEGIN TRANSACTION");
  try {
    const res = fn();
    exec("COMMIT");
    return res;
  } catch (e) {
    exec("ROLLBACK");
    throw e;
  }
}

